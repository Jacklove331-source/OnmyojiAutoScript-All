# 商店费用曲线（游戏内实测，不是从攻略抄的）
# 数据来源：5 局真实日志、约 1900 张商店卡，用
#   dev_tools/chess_shop_cost_curve.py 按阶统计「实际出现过的最高费用」。
# 阶1 → 只有 1 费；阶2~3 → 最高 2 费（1 费占 78~100%）；
# 阶4 → 3 费（1 费占 52~67%）；阶5~6 → 4 费（1 费占 29~53%）；
# 阶7~8 → 5 费（1 费占 15~26%）。
# 用途：前期阵容必须留「当期买得到的低费位」，否则前 10 回合买不到卡、
#       棋盘空着（实测前 10 回合 0~3 次购买、0 次上阵）。
SHOP_MAX_COST_BY_LEVEL = {1: 1, 2: 2, 3: 2, 4: 3, 5: 4, 6: 4, 7: 5, 8: 5, 9: 5}
SHOP_COST_CURVE_SOURCE = (
    'dev_tools/chess_shop_cost_curve.py 统计 chess5 / chess7 / '
    'chess_series3_run3 / chess_validate1 / chess_validate2 五份日志'
)
SHOP_COST_FALLBACK = 2
SHOP_COST_UNKNOWN_LEVEL_FALLBACK = 3


def shop_max_cost(level) -> int:
    """该阶商店实际能出的最高费用（实测曲线；异常输入给保守值）。"""
    try:
        level = int(level)
    except (TypeError, ValueError):
        return SHOP_COST_FALLBACK
    if level <= 0:
        return SHOP_COST_FALLBACK
    return SHOP_MAX_COST_BY_LEVEL.get(level, SHOP_COST_UNKNOWN_LEVEL_FALLBACK)


